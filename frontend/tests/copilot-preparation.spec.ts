test('copilot can choose more than five findings or the entire assessment', async ({page}) => {
  await page.goto('/');
  await page.getByLabel('Email',{exact:true}).fill('admin@labquality.local');
  await page.getByLabel('Palavra-passe',{exact:true}).fill('Local-e2e-test-only-2026!');
  await page.getByRole('button',{name:'Entrar no espaço de trabalho'}).click();
  await page.route('**/api/v1/ai/readiness/**', async route => {
    const response=await route.fetch();
    const check=await response.json();
    const extra=Array.from({length:4},(_,i)=>({...check.findings[0],id:`synthetic-${i}`,title:`Finding ${i+4}`}));
    const findings=[...check.findings,...extra];
    const url=new URL(route.request().url());
    const ids=url.searchParams.get('all_findings')==='true' ? findings.map(f=>f.id) :
      url.searchParams.getAll('finding_ids').length ? url.searchParams.getAll('finding_ids') : check.selected_ids;
    await route.fulfill({response,json:{...check,findings,finding_count:findings.length,selected_count:ids.length,selected_ids:ids}});
  });
  await page.getByRole('link',{name:'Copiloto de qualidade',exact:true}).click();
  await page.getByLabel('Avaliação de origem').selectOption({index:1});
  await expect(page.locator('.finding-list input[type=checkbox]')).toHaveCount(7);
  const scope=page.getByRole('group',{name:'Âmbito da análise'});
  await scope.getByRole('button',{name:'Todos os achados'}).click();
  await expect(scope).toContainText('7 / 7 seleccionados');
  await expect(page.locator('.finding-list')).toHaveCount(0);
  await scope.getByRole('button',{name:'Escolher achados'}).click();
  for (let i=3;i<7;i++) await page.locator('.finding-list input[type=checkbox]').nth(i).check();
  await expect(scope).toContainText('7 / 7 seleccionados');
  await expect(page.locator('.finding-list input[type=checkbox]:checked')).toHaveCount(7);
  await expect(page.locator('.copilot-submit')).toContainText('3 pedidos');
});

test('reference import keeps readable spacing and previews without saving', async ({page}, testInfo) => {
  await page.goto('/');
  await page.getByLabel('Email',{exact:true}).fill('admin@labquality.local');
  await page.getByLabel('Palavra-passe',{exact:true}).fill('Local-e2e-test-only-2026!');
  await page.getByRole('button',{name:'Entrar no espaço de trabalho'}).click();
  await page.getByRole('link',{name:'Documentos',exact:true}).click();
  const packPanel=page.locator('.source-pack');
  const description=await packPanel.locator('.source-pack-description').boundingBox();
  const upload=await packPanel.locator('.source-pack-upload').boundingBox();
  const actions=await packPanel.locator('.source-pack-actions').boundingBox();
  const panel=await packPanel.boundingBox();
  expect(description && upload && actions && panel).toBeTruthy();
  expect(upload!.y-description!.y-description!.height).toBeGreaterThanOrEqual(12);
  expect(actions!.y-upload!.y-upload!.height).toBeGreaterThanOrEqual(12);
  expect(upload!.x-panel!.x).toBeGreaterThanOrEqual(16);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await expect(packPanel.getByLabel('Pacote de referências SLIPTA (.json)',{exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('documents-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  const pack={pack_version:'slipta-sources-v1',provenance:{pdf_sha256:'synthetic-test-source'},documents:[{code:'SLIPTA-TEST-1.1',title:'Synthetic reference for UI validation',content:'This synthetic reference supports only an automated application workflow test.',criterion_codes:['1.1']}]};
  await page.getByLabel('Pacote de referências SLIPTA (.json)',{exact:true}).setInputFiles({name:'sources.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(pack))});
  await page.getByRole('button',{name:'Pré-validar referências',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Pré-validação sem gravação.'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Synthetic reference for UI validation',exact:false})).toHaveCount(0);
  await page.getByRole('button',{name:'Importar rascunhos',exact:true}).click();
  await page.getByLabel('Pesquisar documentos',{exact:true}).fill('SLIPTA-TEST-1.1');
  const card=page.locator('.document-card').filter({hasText:'Synthetic reference for UI validation'});
  await expect(card).toBeVisible();
  await expect(card.locator('.badge')).toHaveText('Rascunho');
  await card.click();
  await page.getByRole('button',{name:'Submeter à revisão',exact:true}).click();
  await page.locator('.document-card').filter({hasText:'Synthetic reference for UI validation'}).click();
  await expect(page.getByText('A aprovação deve ser feita por outra pessoa autorizada.',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Aprovar documento',exact:true})).toHaveCount(0);
});
