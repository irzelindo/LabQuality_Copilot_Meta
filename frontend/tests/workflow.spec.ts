test("justified NA excludes points in an applicable instrument", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("Email", { exact: true }).fill("admin@labquality.local");
  await page.getByLabel("Palavra-passe", { exact: true }).fill("Local-e2e-test-only-2026!");
  await page.getByRole("button", { name: "Entrar no espaço de trabalho" }).click();
  await page.getByRole("link", { name: "Instrumentos", exact: true }).click();
  await page.getByRole("button", { name: "Publicar instrumento" }).click();
  const instrument = page.getByRole("dialog");
  await instrument.getByLabel("Código", { exact: true }).fill("CHECK-UI");
  await instrument.getByLabel("Versão", { exact: true }).fill("1");
  await instrument.getByLabel("Nome", { exact: true }).fill("Checklist applicability UI");
  await instrument.getByLabel("Regra de pontuação").selectOption("sum_applicable_v1");
  await instrument.getByLabel("Código único").first().fill("A1");
  await instrument.getByLabel("Secção").first().fill("Documentos");
  await instrument.getByLabel("Descrição do critério").first().fill("Documentos aplicáveis");
  await instrument.getByRole("button", { name: "Adicionar critério" }).click();
  await instrument.getByLabel("Código único").last().fill("A2");
  await instrument.getByLabel("Secção").last().fill("Documentos");
  await instrument.getByLabel("Descrição do critério").last().fill("Controlo das versões");
  await instrument.getByRole("button", { name: "Publicar versão" }).click();
  await expect(page.getByRole("row").filter({ hasText: "CHECK-UI" })).toBeVisible();
  await page.getByRole("link", { name: "Avaliações", exact: true }).click();
  await page.getByRole("button", { name: "Nova avaliação" }).click();
  const assessment = page.getByRole("dialog");
  await assessment.getByRole("combobox", { name: "Instrumento" }).selectOption({ label: "CHECK-UI v1" });
  await assessment.getByLabel("Pontuação").first().selectOption("NA");
  await assessment.getByLabel("Comentário").first().fill("Item não aplicável ao laboratório nesta avaliação.");
  await assessment.getByLabel("Pontuação").last().selectOption("2");
  await assessment.getByRole("button", { name: "Guardar avaliação" }).click();
  const row = page.getByRole("row").filter({ hasText: "CHECK-UI" });
  await expect(row).toContainText("100%");
  await row.getByRole("button", { name: "Abrir" }).click();
  const details = page.getByRole("dialog");
  await expect(details.locator(".big-score")).toContainText("2/2 pontos");
  await expect(details.getByText("1 NA", { exact: false })).toBeVisible();
  await expect(details.getByRole("row").filter({ hasText: "A1" })).toContainText("NA");
});
