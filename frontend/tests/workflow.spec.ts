import { test, expect } from "@playwright/test";
import path from "node:path";

test("assessment, filters, idempotent import, action evidence and independent verification", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Bem-vindo de volta." })).toBeVisible();
  await page.getByLabel("Email", { exact: true }).fill("admin@labquality.local");
  await page.getByLabel("Palavra-passe", { exact: true }).fill("Local-e2e-test-only-2026!");
  await page.getByRole("button", { name: "Entrar no espaço de trabalho" }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Visão geral" })).toBeVisible();
  await expect(page.locator(".metric").first()).toContainText("63,3%");
  await page.screenshot({ path: testInfo.outputPath("dashboard-desktop.png"), fullPage: true });
  await page.locator("#global-lab").selectOption({ label: "Laboratório Sul" });
  await expect(page.locator(".metric").first()).toContainText("80%");
  await page.locator("#global-lab").selectOption("");
  await page.getByRole("link", { name: "Avaliações", exact: true }).click();
  await expect(page.locator("tbody tr")).toHaveCount(9);
  await page.getByRole("button", { name: "Abrir", exact: true }).first().click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").getByText("DEMO-QMS v1.0", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Close / Fechar", exact: true }).click();
  await page.getByRole("link", { name: "Importar dados", exact: true }).click();
  await page.getByLabel("Ficheiro de avaliações", { exact: true }).setInputFiles(path.join(__dirname, "../public/demo/assessments.csv"));
  await page.getByRole("button", { name: "Pré-validar ficheiro" }).click();
  await expect(page.getByText("Pré-validação concluída — sem gravação", { exact: true })).toBeVisible();
  await expect(page.locator(".import-result")).toContainText("9");
  await page.getByRole("button", { name: "Aplicar importação" }).click();
  await expect(page.getByRole("heading", { name: "Importação aplicada", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Planos de melhoria", exact: true }).click();
  await page.locator(".action-card").first().click();
  await page.getByRole("button", { name: "Iniciar execução", exact: true }).click();
  await expect(page.getByRole("button", { name: "Solicitar verificação", exact: true })).toBeVisible();
  await page.getByRole("dialog").getByLabel("Anexar PDF, PNG, JPEG ou TXT · máximo 10 MB").setInputFiles({ name: "registo-teste.txt", mimeType: "text/plain", buffer: Buffer.from("Evidencia ficticia de verificacao e revisao independente.") });
  await page.getByRole("button", { name: "Guardar evidência", exact: true }).click();
  await expect(page.getByText("registo-teste.txt", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Solicitar verificação", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Verificação independente", exact: true })).toBeVisible();
  await page.getByRole("dialog").getByRole("checkbox").first().check();
  await page.getByLabel("Justificação da verificação", { exact: true }).fill("Evidencia e resultado revistos por outra pessoa autorizada.");
  await page.getByRole("button", { name: "Guardar verificação", exact: true }).click();
  await expect(page.getByRole("dialog").locator(".badge.closed")).toBeVisible();
  await page.getByRole("button", { name: "Close / Fechar", exact: true }).click();
  await page.getByRole("button", { name: "PT", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Improvement plans" })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Menu", exact: true }).click();
  await page.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name: "Overview" })).toBeVisible();
  await expect(page.locator(".metric").first()).toContainText("63,3%");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect.poll(() => page.locator(".sidebar").evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: testInfo.outputPath("dashboard-mobile.png"), fullPage: true });
  expect(errors).toEqual([]);
});
